"""Dataset invariants.

The site list is generated by ``scripts/build_sites.py``, so these tests are
the contract that generator has to keep. A malformed record does not raise at
import time — it silently becomes a site that can never be "found", which is
how coverage quietly rots.
"""

from __future__ import annotations

import re
from urllib.parse import urlparse

import pytest

from spyglass_lite import _registry
from spyglass_lite._http import render

REQUIRED_KEYS = {
    "name",
    "domain",
    "url",
    "probe",
    "method",
    "check",
    "present",
    "absent",
    "tags",
    "source",
}
KNOWN_CHECKS = {"status_code", "message", "response_url"}
KNOWN_METHODS = {"GET", "POST", "PUT", "PATCH", "HEAD"}


@pytest.fixture(scope="module")
def site_list():
    return _registry.sites()


def test_dataset_is_not_empty(site_list):
    assert len(site_list) > 1_000


def test_every_record_has_the_schema(site_list):
    for site in site_list:
        missing = REQUIRED_KEYS - set(site)
        assert not missing, f"{site.get('domain')} is missing {missing}"


def test_domains_are_unique(site_list):
    domains = [site["domain"].lower() for site in site_list]
    duplicates = {d for d in domains if domains.count(d) > 1}
    assert not duplicates


def test_urls_are_absolute_and_templated(site_list):
    for site in site_list:
        assert site["url"].startswith(("http://", "https://")), site["domain"]
        assert "{username}" in site["url"] or "{}" in site["url"], site["domain"]


def test_probes_are_absolute(site_list):
    for site in site_list:
        probe = site["probe"]
        if probe:
            assert probe.startswith(("http://", "https://")), site["domain"]
            assert "{username}" in probe or "{}" in probe or site["payload"], site["domain"]


def test_checks_and_methods_are_known(site_list):
    for site in site_list:
        assert site["check"] in KNOWN_CHECKS, site["domain"]
        assert site["method"] in KNOWN_METHODS, site["domain"]


def test_message_rules_carry_a_marker(site_list):
    """A body rule with neither marker can only ever answer "found"."""
    for site in site_list:
        if site["check"] == "message":
            assert site["present"] or site["absent"], site["domain"]


def test_regexes_compile(site_list):
    for site in site_list:
        if site["regex"]:
            re.compile(site["regex"])


def test_tags_and_sources_are_lists(site_list):
    for site in site_list:
        assert isinstance(site["tags"], list), site["domain"]
        assert isinstance(site["source"], list) and site["source"], site["domain"]
        assert set(site["source"]) <= {"sherlock", "maigret"}, site["domain"]


def test_metadata_matches_the_payload(site_list):
    meta = _registry.dataset_meta()
    counts = meta["counts"]

    assert counts["sites"] == len(site_list)
    assert counts["with_probe"] == sum(1 for s in site_list if s["probe"])
    assert counts["with_markers"] == sum(1 for s in site_list if s["present"] or s["absent"])
    assert counts["from_both"] <= min(counts["from_sherlock"], counts["from_maigret"])


def test_ranks_are_ordered(site_list):
    ranks = [site["rank"] for site in site_list]
    assert ranks == sorted(ranks)


def test_render_quotes_the_handle():
    site = {"url": "https://x.example/u/{username}", "probe": None}
    assert render(site["url"], "a b/c") == "https://x.example/u/a%20b%2Fc"


def test_render_supports_both_placeholders():
    assert render("https://x.example/{}", "me") == "https://x.example/me"


# ─── selection ────────────────────────────────────────────


def test_select_all_returns_everything(site_list):
    assert len(_registry.select()) == len(site_list)


def test_select_only_by_domain(site_list):
    chosen = _registry.select(only=["GitHub"])
    assert [s["domain"] for s in chosen] == ["github.com"]


def test_select_only_is_case_and_www_insensitive():
    chosen = _registry.select(only=["WWW.GitHub.com"])
    assert chosen[0]["domain"] == "github.com"


def test_select_only_accepts_full_urls():
    chosen = _registry.select(only=["https://www.github.com/torvalds"])
    assert [s["domain"] for s in chosen] == ["github.com"]


def test_select_only_accepts_domain_with_path():
    chosen = _registry.select(only=["github.com/login"])
    assert [s["domain"] for s in chosen] == ["github.com"]


def test_select_exclude_by_name_and_domain():
    excluded = {"github.com", "Instagram"}
    chosen = _registry.select(exclude=excluded)
    assert all(
        s["domain"] not in {"github.com", "instagram.com"} and s["name"] not in excluded
        for s in chosen
    )
    assert len(chosen) < len(_registry.sites())


def test_select_limit_keeps_the_most_popular():
    head = _registry.select(limit=10)
    assert len(head) == 10
    assert [s["domain"] for s in head] == [s["domain"] for s in _registry.sites()[:10]]


def test_select_limit_applies_after_filters():
    chosen = _registry.select(tags=["coding"], limit=5)
    assert 0 < len(chosen) <= 5
    assert all("coding" in s["tags"] for s in chosen)


def test_select_unknown_tag_is_empty():
    assert _registry.select(tags=["definitely-not-a-tag"]) == []


def test_unknown_only_is_empty():
    assert _registry.select(only=["nope.example"]) == []


def test_curated_entries_use_a_json_probe(site_list):
    """Curated overrides exist because the HTML route is bot-walled."""
    curated = [site for site in site_list if site.get("curated")]
    assert curated
    for site in curated:
        assert site["probe"], site["domain"]
        assert site["check"] == "status_code", site["domain"]


def test_registrations_have_the_recipe_schema():
    recipes = _registry.registrations()
    assert recipes
    ids = [recipe["id"] for recipe in recipes]
    assert len(ids) == len(set(ids))
    for recipe in recipes:
        assert recipe["url"].startswith(("http://", "https://")), recipe["id"]
        assert "{email}" in recipe["url"] or recipe.get("payload") or recipe.get("params")
        assert recipe.get("exists_when") or recipe.get("absent_when")


def test_supporting_datasets_load():
    assert len(_registry.disposable_domains()) > 100
    assert _registry.providers()
    assert _registry.role_accounts()
    assert all(name for _, name in _registry.providers())


def test_providers_are_sorted_longest_first():
    suffixes = [suffix for suffix, _ in _registry.providers()]
    assert suffixes == sorted(suffixes, key=len, reverse=True)


def test_dataset_meta_has_provenance():
    meta = _registry.dataset_meta()
    assert meta["version"] >= 1
    assert set(meta["sources"]) == {"sherlock", "maigret"}
    for source in meta["sources"].values():
        assert source["license"] == "MIT"
        assert urlparse(source["homepage"]).scheme == "https"
